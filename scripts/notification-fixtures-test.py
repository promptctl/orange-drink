#!/usr/bin/env python3
# [LAW:behavior-not-structure] scripts/notification-fixtures run as a process over captures written here, so what is held is what
# `make notification-fixtures` relies on: the committed captures render to the committed Swift, `record` keeps each distinct reading
# once, `render` groups and escapes as the Swift file is read, and `check` names what wording changed. No VM, no Accessibility.
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SCRIPT = HERE / "notification-fixtures"
FIXTURES = HERE.parent / "Tests" / "OrangeDrinkTests" / "NotificationFixtures.swift"
failures = []


def run(*arguments):
    return subprocess.run([sys.executable, "-I", str(SCRIPT), *map(str, arguments)], capture_output=True, text=True)


def holds(name, condition, detail=""):
    print(("ok: " if condition else "FAILED: ") + name)
    if not condition:
        failures.append(f"{name}\n{detail}")


def capture(directory, name, version, *records):
    path = pathlib.Path(directory) / name
    path.write_text(f"macos\t{version}\n" + "".join("\t".join(record) + "\n" for record in records), encoding="utf-8")
    return path


ALERT = ("AXNotificationCenterAlert", "Low Battery", "Soon.", "Low Battery, Soon.", "AXPress", "Name:Close")
STACK = ("AXNotificationCenterBannerStack", "Low Battery", "Soon.", "Mail, Low Battery, Soon., stacked", "AXPress", "Name:Clear All")
FRENCH = ("AXNotificationCenterAlert", "Batterie faible", "Branchez.", "Batterie faible, Branchez.", "AXPress", "Name:Fermer")
ARABIC = ("AXNotificationCenterAlert", "شحن", "سيتم", "‏⁨شحن⁩، ⁨سيتم⁩", "AXPress", "Name:إغلاق")
QUOTED = ("AXNotificationCenterBanner", 'Say "hi"', "back\\slash", "Mail", "AXPress")


def row(step, record):
    return (step, *record)


with tempfile.TemporaryDirectory() as scratch:
    scratch = pathlib.Path(scratch)

    # The generated file and its source cannot drift apart: the committed captures render to it byte for byte.
    rendered = run("render")
    holds("the committed captures render to NotificationFixtures.swift", rendered.stdout == FIXTURES.read_text(encoding="utf-8"), rendered.stderr)

    # A newer macOS that changed one reading and kept the others; an older one with a reading of its own.
    older = capture(scratch, "older", "14.2", row("final", ALERT), row("final", ALERT), row("panel", STACK), row("language-fr", ARABIC), row("language-fr", QUOTED))
    newer = capture(scratch, "newer", "26.6.2", row("final", ALERT), row("panel", ALERT), row("panel", STACK), row("language-fr", FRENCH))
    committed = scratch / "committed"
    recorded = run("--captures", committed, "record", older, newer)
    holds("record succeeds", recorded.returncode == 0, recorded.stderr)
    holds("record keeps the first reading of each distinct record, tagged with its step",
          (committed / "macos-14.tsv").read_text(encoding="utf-8").split("\n")[:-1]
          == ["macos\t14.2"] + ["\t".join(r) for r in (row("final", ALERT), row("panel", STACK), row("language-fr", ARABIC), row("language-fr", QUOTED))])
    again = scratch / "again"
    run("--captures", again, "record", committed / "macos-14.tsv", committed / "macos-26.tsv")
    holds("a committed capture records to itself",
          all((committed / f"macos-{m}.tsv").read_text(encoding="utf-8") == (again / f"macos-{m}.tsv").read_text(encoding="utf-8") for m in (14, 26)))

    expected = """@testable import OrangeDrink

// Generated by `make notification-fixtures` from scripts/notification-captures; edit those, never this file.
// What NotificationCenter's accessibility tree showed on macOS 26.6.2, 14.2.
// ControlCenter's own code posted the low battery alerts, and Script Editor the others. Bidi marks are written as escapes.
enum NotificationFixtures {
    static let lowBatteryAlerts = [
        // macOS 14, 26
        NotificationValues(subrole: "AXNotificationCenterAlert", title: "Low Battery", body: "Soon.",
                           description: "Low Battery, Soon.",
                           actions: ["AXPress", "Name:Close"]),
        // macOS 26
        NotificationValues(subrole: "AXNotificationCenterAlert", title: "Batterie faible", body: "Branchez.",
                           description: "Batterie faible, Branchez.",
                           actions: ["AXPress", "Name:Fermer"]),
        // macOS 14
        NotificationValues(subrole: "AXNotificationCenterAlert", title: "شحن", body: "سيتم",
                           description: "\\u{200F}\\u{2068}شحن\\u{2069}، \\u{2068}سيتم\\u{2069}",
                           actions: ["AXPress", "Name:إغلاق"]),
    ]

    static let otherApps = [
        // macOS 14, 26
        NotificationValues(subrole: "AXNotificationCenterBannerStack", title: "Low Battery", body: "Soon.",
                           description: "Mail, Low Battery, Soon., stacked",
                           actions: ["AXPress", "Name:Clear All"]),
        // macOS 14
        NotificationValues(subrole: "AXNotificationCenterBanner", title: "Say \\"hi\\"", body: "back\\\\slash",
                           description: "Mail",
                           actions: ["AXPress"]),
    ]
}
"""
    holds("render groups identical records across majors, newest first, and escapes", run("--captures", committed, "render").stdout == expected,
          run("--captures", committed, "render").stdout)

    holds("check passes over the capture it was recorded from", run("--captures", committed, "check", older, newer).returncode == 0)
    reworded = capture(scratch, "reworded", "26.7", row("final", ("AXNotificationCenterAlert", "Low Battery", "Later.", "Low Battery, Later.", "AXPress", "Name:Close")),
                       row("panel", STACK), row("language-fr", FRENCH))
    checked = run("--captures", committed, "check", reworded)
    holds("check names the wording that changed and the wording that went", checked.returncode != 0 and "Later." in checked.stderr
          and "shown now, not committed" in checked.stderr and "committed, not shown now" in checked.stderr and "Soon." in checked.stderr, checked.stderr)
    reordered = capture(scratch, "reordered", "26.8", row("language-fr", FRENCH), row("final", ALERT), row("panel", STACK))
    holds("check names a changed order", "another order" in run("--captures", committed, "check", reordered).stderr)
    unknown = capture(scratch, "unknown", "27.0", row("final", ALERT))
    holds("check refuses a macOS it has no capture of", "macOS 27: no committed capture" in run("--captures", committed, "check", unknown).stderr)

    # Anything malformed is refused with its file and line, and nothing is written.
    untouched = scratch / "untouched"
    for name, text, where in [
        ("no macos line", "final\tAXNotificationCenterAlert\ta\tb\tc\n", ":1:"),
        ("a short record", "macos\t26.1\nfinal\tAXNotificationCenterAlert\ta\tb\n", ":2:"),
        ("a subrole of another kind", "macos\t26.1\nfinal\tAXButton\ta\tb\tc\n", ":2:"),
        ("an empty step", "macos\t26.1\n\tAXNotificationCenterAlert\ta\tb\tc\n", ":2:"),
        ("no records", "macos\t26.1\n", "no records"),
    ]:
        bad = scratch / "bad"
        bad.write_text(text, encoding="utf-8")
        refused = run("--captures", untouched, "record", older, bad)
        holds(f"record refuses {name} naming where, and writes nothing", refused.returncode != 0 and where in refused.stderr and not untouched.exists(), refused.stderr)
    twice = run("--captures", untouched, "record", older, capture(scratch, "second", "14.9", row("final", ALERT)))
    holds("record refuses two captures of one major", twice.returncode != 0 and "two captures of one macOS major" in twice.stderr and not untouched.exists(), twice.stderr)

if failures:
    sys.exit("\n".join(failures))
